// --- Output: the Meta() methods ----------------------------------------------

func writeMetaGo(path, pkg string, models []model) error {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by %s; DO NOT EDIT.\n\n", generatedBy)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "import %q\n\n", DbhImportPath)

	for _, m := range models {
		t := m.Meta
		fmt.Fprintf(&b, "func (m *%s) Meta() dbh.TableMeta {\n", m.Struct)
		b.WriteString("return dbh.TableMeta{\n")
		fmt.Fprintf(&b, "Table: %q,\n", t.Table)
		if t.Group != "" {
			fmt.Fprintf(&b, "Group: %q,\n", t.Group)
		}

		b.WriteString("Fields: []dbh.TableMetaField{\n")
		for _, f := range t.Fields {
			b.WriteString("{" + strings.Join(fieldParts(f), ", ") + "},\n")
		}
		b.WriteString("},\n")

		if len(t.Indexes) > 0 {
			b.WriteString("Indexes: []dbh.TableMetaIndex{\n")
			for _, ix := range t.Indexes {
				fmt.Fprintf(&b, "{Columns: %s", stringSlice(ix.Columns))
				if ix.Unique {
					b.WriteString(", Unique: true")
				}
				b.WriteString("},\n")
			}
			b.WriteString("},\n")
		}

		if len(t.ForeignKeys) > 0 {
			b.WriteString("ForeignKeys: []dbh.TableMetaFK{\n")
			for _, fk := range t.ForeignKeys {
				fmt.Fprintf(&b, "{Columns: %s, RefTable: %q, RefColumns: %s},\n",
					stringSlice(fk.Columns), fk.RefTable, stringSlice(fk.RefColumns))
			}
			b.WriteString("},\n")
		}

		if len(t.Constraints) > 0 {
			b.WriteString("Constraints: []string{\n")
			for _, c := range t.Constraints {
				fmt.Fprintf(&b, "%q,\n", c)
			}
			b.WriteString("},\n")
		}

		if len(t.ExtraColumns) > 0 {
			b.WriteString("ExtraColumns: []dbh.TableMetaExtraColumn{\n")
			for _, ec := range t.ExtraColumns {
				fmt.Fprintf(&b, "{Name: %q, Type: dbh.%s", ec.Name, columnTypeName(ec.Type))
				if ec.MaxSize > 0 {
					fmt.Fprintf(&b, ", MaxSize: %d", ec.MaxSize)
				}
				if ec.After != "" {
					fmt.Fprintf(&b, ", After: %q", ec.After)
				}
				if ec.NotNull {
					b.WriteString(", NotNull: true")
				}
				if ec.Unique {
					b.WriteString(", Unique: true")
				}
				if ec.Default != nil {
					b.WriteString(", Default: " + stringPtr(*ec.Default))
				}
				b.WriteString("},\n")
			}
			b.WriteString("},\n")
		}

		b.WriteString("}\n")
		b.WriteString("}\n\n")
	}

	return writeGoFile(path, b.String())
}

// fieldParts returns the "Key: value" pieces of one TableMetaField literal,
// leaving out everything that holds its zero value.
func fieldParts(f dbh.TableMetaField) []string {
	parts := []string{
		fmt.Sprintf("Name: %q", f.Name),
		fmt.Sprintf("GoField: %q", f.GoField),
	}
	add := func(cond bool, s string) {
		if cond {
			parts = append(parts, s)
		}
	}
	add(f.Type != dbh.TypeUnknown, "Type: dbh."+columnTypeName(f.Type))
	add(f.MaxSize > 0, fmt.Sprintf("MaxSize: %d", f.MaxSize))
	add(f.AutoInc, "AutoInc: true")
	add(f.NotNull, "NotNull: true")
	add(f.Unique, "Unique: true")
	add(f.IsPrimaryKey, "IsPrimaryKey: true")
	if f.Default != nil {
		parts = append(parts, "Default: "+stringPtr(*f.Default))
	}
	add(f.IsIgnore, "IsIgnore: true")
	add(f.IsPrivate, "IsPrivate: true")

	switch f.Trim {
	case dbh.TrimBoth:
		parts = append(parts, "Trim: dbh.TrimBoth")
	case dbh.TrimLeft:
		parts = append(parts, "Trim: dbh.TrimLeft")
	case dbh.TrimRight:
		parts = append(parts, "Trim: dbh.TrimRight")
	}
	switch f.Case {
	case dbh.CaseUpper:
		parts = append(parts, "Case: dbh.CaseUpper")
	case dbh.CaseLower:
		parts = append(parts, "Case: dbh.CaseLower")
	}
	switch f.Overflow {
	case dbh.OverflowTruncate:
		parts = append(parts, "Overflow: dbh.OverflowTruncate")
	case dbh.OverflowError:
		parts = append(parts, "Overflow: dbh.OverflowError")
	}

	add(f.ZeroToNull, "ZeroToNull: true")
	add(f.InvalidToNull, "InvalidToNull: true")
	add(f.ValidateJSON, "ValidateJSON: true")
	add(f.ValidateDate, "ValidateDate: true")
	add(f.ValidateTime, "ValidateTime: true")
	add(f.JSONTag != "", fmt.Sprintf("JSONTag: %q", f.JSONTag))
	return parts
}

func columnTypeName(t dbh.ColumnType) string {
	switch t {
	case dbh.TypeBigInt:
		return "TypeBigInt"
	case dbh.TypeInt:
		return "TypeInt"
	case dbh.TypeTinyInt:
		return "TypeTinyInt"
	case dbh.TypeVarchar:
		return "TypeVarchar"
	case dbh.TypeText:
		return "TypeText"
	case dbh.TypeDate:
		return "TypeDate"
	case dbh.TypeTimestamp:
		return "TypeTimestamp"
	case dbh.TypeJSON:
		return "TypeJSON"
	}
	return "TypeUnknown"
}

func stringSlice(ss []string) string {
	quoted := make([]string, len(ss))
	for i, s := range ss {
		quoted[i] = fmt.Sprintf("%q", s)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

// stringPtr returns a Go expression of type *string holding s. It is an
// inline function literal on purpose: a named helper would be declared once
// per generated file, and two files in one package would collide.
func stringPtr(s string) string {
	return fmt.Sprintf("func() *string { s := %q; return &s }()", s)
}

// --- Output: the model list --------------------------------------------------

func writeListGo(path, pkg, listVar, group string, models []model) error {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by %s; DO NOT EDIT.\n\n", generatedBy)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "import %q\n\n", DbhImportPath)

	if group == "" {
		fmt.Fprintf(&b, "// %s lists one instance of every model, in dependency order: a model\n", listVar)
	} else {
		fmt.Fprintf(&b, "// %s lists one instance of every model of group %q, in dependency order: a model\n", listVar, group)
	}
	b.WriteString("// comes after the models its foreign keys point to. Iterate it and call\n")
	b.WriteString("// Meta().BuildCreateTable, BuildIndexes and BuildAlterFKs to create the schema.\n")
	fmt.Fprintf(&b, "var %s = []dbh.HasMeta{\n", listVar)
	for _, m := range models {
		fmt.Fprintf(&b, "&%s{},\n", m.Struct)
	}
	b.WriteString("}\n")

	return writeGoFile(path, b.String())
}

// writeGoFile formats src with gofmt rules and writes it.
func writeGoFile(path, src string) error {
	out, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("formatting generated code: %w", err)
	}
	return os.WriteFile(path, out, 0644)
}

// --- Output: the SQL scripts -------------------------------------------------

// sqlFileName is "<dialect>.sql", or "<group>.<dialect>.sql" when the output
// is restricted to a group, so the scripts of several groups can share a
// folder.
func sqlFileName(group string, d dbh.DbType) string {
	if group == "" {
		return d.String() + ".sql"
	}
	return group + "." + d.String() + ".sql"
}

// writeSQL writes the CREATE TABLE and CREATE INDEX statements of the models,
// in order, built by the very functions an application runs.
//
// MySQL foreign keys are not part of the script: they need every table to
// exist first, so the application applies them last with BuildAlterFKs.
func writeSQL(path string, d dbh.DbType, group string, models []model) error {
	var b strings.Builder
	fmt.Fprintf(&b, "-- Generated by %s; %s dialect", generatedBy, d)
	if group != "" {
		fmt.Fprintf(&b, "; group %s", group)
	}
	b.WriteString("\n\n")

	for _, m := range models {
		b.WriteString(m.Meta.BuildCreateTable(d))
		b.WriteString(";\n\n")
		for _, stmt := range m.Meta.BuildIndexes(d) {
			b.WriteString(stmt)
			b.WriteString(";\n")
		}
		b.WriteString("\n")
	}

	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(b.String()), 0644)
}
