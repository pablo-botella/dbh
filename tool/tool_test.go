// newModelDir writes the three model sources into a fresh folder.
func newModelDir(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	write(t, filepath.Join(dir, "customer_mdl.go"), customerSrc)
	write(t, filepath.Join(dir, "order_mdl.go"), orderSrc)
	write(t, filepath.Join(dir, "setting_mdl.go"), settingSrc)
	// A plain source without directive, and a test file: both ignored.
	write(t, filepath.Join(dir, "helpers.go"), "package shop\n\nfunc helper() {}\n")
	write(t, filepath.Join(dir, "broken_test.go"), "this is not Go\n")
	return dir
}

func write(t *testing.T, path, content string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		t.Fatal(err)
	}
}

func read(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func mustContain(t *testing.T, where, text string, wanted ...string) {
	t.Helper()
	for _, w := range wanted {
		if !strings.Contains(text, w) {
			t.Errorf("%s: missing %q in:\n%s", where, w, text)
		}
	}
}

func mustParse(t *testing.T, path string) {
	t.Helper()
	if _, err := parser.ParseFile(token.NewFileSet(), path, nil, 0); err != nil {
		t.Errorf("%s is not valid Go: %v", path, err)
	}
}

func TestRunWritesEverything(t *testing.T) {
	dir := newModelDir(t)
	sqlDir := filepath.Join(t.TempDir(), "ddl")

	res, err := Run(Options{
		Dir:      dir,
		MetaFile: "generated_meta.go",
		ListFile: "generated_list.go",
		SQLDir:   sqlDir,
	})
	if err != nil {
		t.Fatal(err)
	}
	if res.Models != 3 || len(res.Files) != 4 {
		t.Fatalf("result: %+v", res)
	}

	// --- Meta() methods
	metaPath := filepath.Join(dir, "generated_meta.go")
	mustParse(t, metaPath)
	meta := read(t, metaPath)
	mustContain(t, "meta", meta,
		"// Code generated by dbh-table-meta; DO NOT EDIT.",
		"package shop",
		`import "github.com/pablo-botella/dbh"`,
		"func (m *Customer_mdl) Meta() dbh.TableMeta {",
		`Table: "customers",`,
		`Group: "sales",`,
		`{Name: "id", GoField: "Id", Type: dbh.TypeBigInt, AutoInc: true, NotNull: true, IsPrimaryKey: true, JSONTag: "id"},`,
		`{Name: "name", GoField: "Name", Type: dbh.TypeVarchar, MaxSize: 40, NotNull: true, Unique: true, Trim: dbh.TrimBoth, Overflow: dbh.OverflowTruncate, JSONTag: "name"},`,
		`Default: func() *string { s := "'US'"; return &s }(), Case: dbh.CaseUpper},`,
		`{Name: "photo", GoField: "Photo", Type: dbh.TypeText, IsIgnore: true},`,
		`{Columns: []string{"country"}},`,
		`"name NOT NULL",`,
		`{Name: "thumbnail", Type: dbh.TypeText, After: "photo"},`,
		`{Name: "placed", GoField: "Placed_on", Type: dbh.TypeDate, InvalidToNull: true, ValidateDate: true},`,
		`{Columns: []string{"id_customer", "placed"}, Unique: true},`,
		`{Columns: []string{"id_customer"}, RefTable: "customers", RefColumns: []string{"id"}},`,
	)
	if strings.Contains(meta, "cache") {
		t.Error("a field without sql tag must not become a column")
	}

	// --- Model list, in dependency order: customers before orders.
	listPath := filepath.Join(dir, "generated_list.go")
	mustParse(t, listPath)
	list := read(t, listPath)
	mustContain(t, "list", list, "var AllMdls = []dbh.HasMeta{", "&Customer_mdl{},", "&Order_mdl{},", "&Setting_mdl{},")
	if strings.Index(list, "&Customer_mdl{}") > strings.Index(list, "&Order_mdl{}") {
		t.Error("customers must come before orders, which reference them")
	}

	// --- SQL scripts
	lite := read(t, filepath.Join(sqlDir, "sqlite.sql"))
	mustContain(t, "sqlite", lite,
		"-- Generated by dbh-table-meta; sqlite dialect\n",
		"CREATE TABLE IF NOT EXISTS customers (\n  id INTEGER PRIMARY KEY AUTOINCREMENT,\n  name TEXT NOT NULL UNIQUE,\n  country TEXT DEFAULT 'US',\n  photo TEXT,\n  thumbnail TEXT\n);\n",
		"CREATE INDEX IF NOT EXISTS idx_customers_country ON customers (country);\n",
		"  FOREIGN KEY (id_customer) REFERENCES customers(id)\n);\n",
		"CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_id_customer_placed ON orders (id_customer, placed);\n",
		"CREATE TABLE IF NOT EXISTS settings (\n  k TEXT PRIMARY KEY,\n  v TEXT\n);\n",
	)

	my := read(t, filepath.Join(sqlDir, "mysql.sql"))
	mustContain(t, "mysql", my,
		"-- Generated by dbh-table-meta; mysql dialect\n",
		"  name VARCHAR(40) NOT NULL UNIQUE,\n",
		"  PRIMARY KEY (id)\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;\n",
		"CREATE UNIQUE INDEX idx_orders_id_customer_placed ON orders (id_customer, placed);\n",
	)
	if strings.Contains(my, "FOREIGN KEY") {
		t.Error("the mysql script must not carry foreign keys: the application applies them last")
	}
}

func TestRunGroupFiltersEveryOutput(t *testing.T) {
	dir := newModelDir(t)
	sqlDir := t.TempDir()

	res, err := Run(Options{
		Dir:      dir,
		MetaFile: "generated_meta_system.go",
		ListFile: "generated_list_system.go",
		ListVar:  "SystemMdls",
		SQLDir:   sqlDir,
		Dialects: "mysql",
		Group:    "system",
	})
	if err != nil {
		t.Fatal(err)
	}
	if res.Models != 1 || len(res.Files) != 3 {
		t.Fatalf("result: %+v", res)
	}

	meta := read(t, filepath.Join(dir, "generated_meta_system.go"))
	list := read(t, filepath.Join(dir, "generated_list_system.go"))
	sql := read(t, filepath.Join(sqlDir, "system.mysql.sql"))

	mustContain(t, "meta", meta, "func (m *Setting_mdl) Meta()")
	mustContain(t, "list", list, "var SystemMdls = []dbh.HasMeta{", "&Setting_mdl{},", `group "system"`)
	mustContain(t, "sql", sql, "; group system\n", "CREATE TABLE IF NOT EXISTS settings (")

	for where, text := range map[string]string{"meta": meta, "list": list, "sql": sql} {
		if strings.Contains(text, "Customer_mdl") || strings.Contains(text, "customers") {
			t.Errorf("%s: a model of another group slipped through", where)
		}
	}
	if _, err := os.Stat(filepath.Join(sqlDir, "system.sqlite.sql")); err == nil {
		t.Error("only the mysql dialect was requested")
	}
}

// Two groups generated into the same package must not collide.
func TestRunGroupsShareAPackage(t *testing.T) {
	dir := newModelDir(t)
	for _, g := range []string{"sales", "system"} {
		_, err := Run(Options{Dir: dir, MetaFile: "generated_meta_" + g + ".go", Group: g})
		if err != nil {
			t.Fatal(err)
		}
	}
	// The second run parses the folder with the first generated file in it.
	sales := read(t, filepath.Join(dir, "generated_meta_sales.go"))
	system := read(t, filepath.Join(dir, "generated_meta_system.go"))
	if strings.Contains(sales, "\nfunc ptrStr") || strings.Contains(system, "\nfunc ptrStr") {
		t.Error("no shared helper may be declared: two files would redeclare it")
	}
	mustContain(t, "sales", sales, "Customer_mdl", "Order_mdl")
	mustContain(t, "system", system, "Setting_mdl")
}

func TestRunWritesOnlyWhatIsAsked(t *testing.T) {
	dir := newModelDir(t)
	sqlDir := t.TempDir()

	res, err := Run(Options{Dir: dir, SQLDir: sqlDir, Dialects: "sqlite"})
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Files) != 1 || filepath.Base(res.Files[0]) != "sqlite.sql" {
		t.Fatalf("files: %v", res.Files)
	}
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		if strings.HasPrefix(e.Name(), "generated") {
			t.Errorf("no Go file was asked for, yet %s appeared", e.Name())
		}
	}
}

func TestRunErrors(t *testing.T) {
	dir := newModelDir(t)

	cases := []struct {
		name string
		opts Options
		want string
	}{
		{"no output", Options{Dir: dir}, "nothing to generate"},
		{"unknown group", Options{Dir: dir, MetaFile: "m.go", Group: "nope"}, `no models in group "nope"`},
		{"group is case-sensitive", Options{Dir: dir, MetaFile: "m.go", Group: "Sales"}, `no models in group "Sales"`},
		{"bad dialect", Options{Dir: dir, SQLDir: dir, Dialects: "oracle"}, `unknown dialect "oracle"`},
		{"bad list var", Options{Dir: dir, ListFile: "l.go", ListVar: "not valid"}, "not a valid Go identifier"},
		{"empty folder", Options{Dir: t.TempDir(), MetaFile: "m.go"}, "no models found"},
	}
	for _, c := range cases {
		_, err := Run(c.opts)
		if err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("%s: want an error containing %q, got %v", c.name, c.want, err)
		}
	}
}

func TestParseErrors(t *testing.T) {
	const head = "package shop\n\n//dbh:generate-table-meta-model T\n"
	const info = "\nfunc (m *T) Dbh_generate_table_meta_model_info() string { return `{\"Table\": \"t\"}` }\n"

	cases := []struct {
		name string
		src  string
		want string
	}{
		{"unknown sql token", head + "type T struct { A string `sql:\"varchr(10)\"` }" + info, `unknown token "varchr(10)"`},
		{"bad varchar size", head + "type T struct { A string `sql:\"varchar(x)\"` }" + info, "bad varchar size"},
		{"unknown write token", head + "type T struct { A string `sql:\"text\" write:\"trimm\"` }" + info, `unknown token "trimm"`},
		{"missing info method", head + "type T struct { A string `sql:\"text\"` }\n", "missing method"},
		{"missing struct", head + info, "declares no such struct"},
		{"missing table", head + "type T struct { A string `sql:\"text\"` }\nfunc (m *T) Dbh_generate_table_meta_model_info() string { return `{}` }\n", "missing Table"},
		{"unknown info key", head + "type T struct { A string `sql:\"text\"` }\nfunc (m *T) Dbh_generate_table_meta_model_info() string { return `{\"Table\": \"t\", \"Indexs\": []}` }\n", "unknown field"},
		{"directive without name", "package shop\n\n//dbh:generate-table-meta-model\ntype T struct{}\n", "exactly one struct name"},
	}
	for _, c := range cases {
		dir := t.TempDir()
		write(t, filepath.Join(dir, "t.go"), c.src)
		_, err := Run(Options{Dir: dir, MetaFile: "m.go"})
		if err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("%s: want an error containing %q, got %v", c.name, c.want, err)
		}
	}
}

func TestDuplicateTable(t *testing.T) {
	dir := t.TempDir()
	one := "package shop\n\n//dbh:generate-table-meta-model A\ntype A struct { X string `sql:\"text\"` }\nfunc (m *A) Dbh_generate_table_meta_model_info() string { return `{\"Table\": \"same\"}` }\n"
	two := "package shop\n\n//dbh:generate-table-meta-model B\ntype B struct { X string `sql:\"text\"` }\nfunc (m *B) Dbh_generate_table_meta_model_info() string { return `{\"Table\": \"same\"}` }\n"
	write(t, filepath.Join(dir, "a.go"), one)
	write(t, filepath.Join(dir, "b.go"), two)

	_, err := Run(Options{Dir: dir, MetaFile: "m.go"})
	if err == nil || !strings.Contains(err.Error(), `table "same" already declared`) {
		t.Errorf("got %v", err)
	}
}
